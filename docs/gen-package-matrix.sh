#!/bin/sh
# ============================================================================
#  gen-package-matrix.sh — regenerate docs/package-matrix.md from live indexes
#
#  Availability of a package on a given architecture is decided by the
#  distribution's build farm, not by its source. The only authoritative answer
#  is the per-arch package index (APKINDEX). This script downloads those
#  indexes and reports which NecrOS packages are present per architecture, so
#  the matrix can be verified rather than guessed.
#
#  Usage:
#    sh docs/gen-package-matrix.sh [ALPINE_VERSION]   # default: v3.20
#
#  Needs: curl or wget, tar, awk. Network access to the Alpine mirror (this is
#  typically run in the Alpine CI container, which can reach dl-cdn).
# ============================================================================

# This script emits Markdown; the backticks in printf formats are literal
# Markdown code fences, not shell command substitutions.
# shellcheck disable=SC2016

set -eu

ALPINE_VER="${1:-v3.20}"
MIRROR="https://dl-cdn.alpinelinux.org/alpine"
# Alpine's released architectures (there is NO 32-bit PowerPC here; only
# ppc64le). 32-bit PowerPC — the PowerBook G4 target — is an Adélie Linux
# concern, checked separately against its own mirror.
ARCHES="x86 x86_64 aarch64 armv7 ppc64le"

# NecrOS package set, grouped. Keep in sync with the installers.
PKGS="nmap tcpdump masscan hping3 arp-scan socat netcat-openbsd nftables \
tshark wireshark xorg-server i3wm rofi rxvt-unicode \
aircrack-ng reaver hashcat rtl-sdr gnuradio gqrx bluez \
nikto hydra john gobuster dirb proxychains-ng tor \
gdb radare2 binwalk ltrace strace \
suricata fail2ban rkhunter chkrootkit clamav yara lynis sleuthkit foremost \
exiftool ldns-tools steghide gnupg imagemagick"

_dl() {
    # _dl URL -> stdout
    if command -v curl >/dev/null 2>&1; then
        curl -fsSL --max-time 90 "$1"
    else
        wget -qO- "$1"
    fi
}

_tmp="$(mktemp -d 2>/dev/null || echo "/tmp/necros-matrix-$$")"
trap 'rm -rf "$_tmp"' EXIT INT TERM

# Collect the package set available on each architecture.
for _arch in $ARCHES; do
    : >"$_tmp/$_arch"
    for _repo in main community; do
        _url="$MIRROR/$ALPINE_VER/$_repo/$_arch/APKINDEX.tar.gz"
        _dl "$_url" 2>/dev/null | tar xzO APKINDEX 2>/dev/null |
            awk -F: '/^P:/ {print $2}' >>"$_tmp/$_arch" || true
    done
    sort -u "$_tmp/$_arch" -o "$_tmp/$_arch"
done

_has() { grep -qx "$2" "$_tmp/$1" 2>/dev/null; }

# Emit markdown.
printf '<!-- generated by docs/gen-package-matrix.sh — do not edit by hand -->\n'
printf '# Alpine package availability by architecture (%s)\n\n' "$ALPINE_VER"
printf 'Generated: %s\n\n' "$(date -u '+%Y-%m-%d %H:%M UTC')"
printf '| Package |'
for _arch in $ARCHES; do printf ' %s |' "$_arch"; done
printf '\n|---|'
for _arch in $ARCHES; do printf '%s' '---|'; done
printf '\n'
for _pkg in $PKGS; do
    printf '| `%s` |' "$_pkg"
    for _arch in $ARCHES; do
        if _has "$_arch" "$_pkg"; then printf ' ✓ |'; else printf ' — |'; fi
    done
    printf '\n'
done
printf '\n> No column for 32-bit PowerPC: Alpine does not build it. For the\n'
printf '> PowerBook G4 (ppc32) see Adélie Linux — docs/powerbook-g4.md.\n'
